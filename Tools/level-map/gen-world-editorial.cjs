// Gera WorldMapEditorial.cs a partir de brainstorm-200-fases.json (dados editoriais, nao validados por balanceamento).
const fs = require('fs'), path = require('path');
const j = require('./brainstorm-200-fases.json');
const diff = j.levels.map(l => l.plannedDifficulty === 'normal' ? 'n' : l.plannedDifficulty === 'difícil' ? 'h' : 'v').join('');
const hard = j.levels.filter(l => l.hardTilePatch).map(l => l.number).join(', ');
const titles = j.chapters.map(c => `            "${c.title}"`).join(',\n');
const out = `// <auto-generated> por Tools/level-map/gen-world-editorial.cjs a partir de brainstorm-200-fases.json.
// Dificuldade e trechos de ladrilho sao proposta editorial de ritmo visual, NAO classificacao validada dos tabuleiros.
namespace RoyalAves.Meta.WorldMap
{
    public static class WorldMapEditorial
    {
        public const int Positions = ${j.levels.length};
        public const int LevelsPerChapter = 20;
        // n = normal, h = dificil, v = muito dificil (indice 0 = fase 1)
        public const string Difficulty = "${diff}";
        public static readonly int[] HardTileLevels = { ${hard} };
        public static readonly string[] ChapterTitles =
        {
${titles}
        };

        public static char DifficultyOf(int level) =>
            level >= 1 && level <= Difficulty.Length ? Difficulty[level - 1] : 'n';

        public static bool HasHardTiles(int level) => System.Array.IndexOf(HardTileLevels, level) >= 0;
    }
}
`;
fs.writeFileSync(path.join(__dirname, '../../Assets/RoyalAves/Scripts/Meta/WorldMap/WorldMapEditorial.cs'), out);
console.log('ok', diff.length);
